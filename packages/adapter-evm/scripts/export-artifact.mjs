// Copies the Foundry build of ReceptumEscrow into src/artifact.ts (run after `forge build`).
import { readFileSync, writeFileSync } from "node:fs";

const out = JSON.parse(
  readFileSync(
    new URL("../contracts/out/ReceptumEscrow.sol/ReceptumEscrow.json", import.meta.url),
    "utf8",
  ),
);
const src = `// Generated by scripts/export-artifact.mjs from contracts/ReceptumEscrow.sol (solc 0.8.30, optimizer 200). Do not edit.
export const receptumEscrowAbi = ${JSON.stringify(out.abi, null, 2)} as const;

export const receptumEscrowBytecode = "${out.bytecode.object}" as const;

/** Runtime code, used by verifiers to recognise genuine ReceptumEscrow deployments. */
export const receptumEscrowDeployedBytecode = "${out.deployedBytecode.object}" as const;
`;
writeFileSync(new URL("../src/artifact.ts", import.meta.url), src);
console.log("wrote src/artifact.ts");
